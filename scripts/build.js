const fs = require("node:fs");
const path = require("node:path");
const { getGreeting } = require("../src/index");

const outputDir = path.join(__dirname, "..", "dist");
fs.mkdirSync(outputDir, { recursive: true });

const appSource = `// Generated by npm run build\n${fs.readFileSync(
  path.join(__dirname, "..", "src", "index.js"),
  "utf8"
)}`;

fs.writeFileSync(path.join(outputDir, "index.js"), appSource);

const buildInfo = {
  application: "github-actions-npm-artifact-project",
  version: require("../package.json").version,
  builtAt: new Date().toISOString(),
  sampleOutput: getGreeting()
};

fs.writeFileSync(
  path.join(outputDir, "build-info.json"),
  JSON.stringify(buildInfo, null, 2) + "\n"
);

console.log("Build completed. Files created:");
console.log("- dist/index.js");
console.log("- dist/build-info.json");
